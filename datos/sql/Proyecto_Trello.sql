USE PROYECTO_TRELLO_V2;


CREATE TABLE USUARIOS(
    ID_USUARIO INT AUTO_INCREMENT,
    NOMBRE VARCHAR(50) NOT NULL,
    CORREO VARCHAR(100) NOT NULL,
    CONTRASENA VARCHAR(255) NOT NULL,
    RUT VARCHAR(12) NOT NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY(ID_USUARIO),
    CONSTRAINT UQ_USUARIOS_CORREO UNIQUE(CORREO),
    CONSTRAINT UQ_USUARIOS_RUT UNIQUE(RUT)
);

CREATE TABLE PROYECTO(
    ID_PROYECTO INT AUTO_INCREMENT,
    NOMPRO VARCHAR(50) NOT NULL,
    DESCRIPCION VARCHAR(150) NULL,
    FECHA_CREACION DATE NOT NULL DEFAULT (CURRENT_DATE),
    CONSTRAINT PK_PROYECTO PRIMARY KEY(ID_PROYECTO)
);

CREATE TABLE USUARIO_PROYECTO(
    ID_USUARIO_PROYECTO INT AUTO_INCREMENT,
    ID_USUARIO INT NOT NULL,
    ID_PROYECTO INT NOT NULL,
    ROL VARCHAR(20) NOT NULL,
    FECHA_INGRESO DATE NOT NULL DEFAULT (CURRENT_DATE),
    CONSTRAINT PK_USUARIO_PROYECTO PRIMARY KEY(ID_USUARIO_PROYECTO),
    CONSTRAINT UQ_USUARIO_PROYECTO UNIQUE(ID_USUARIO, ID_PROYECTO),
    CONSTRAINT FK_UP_USUARIOS FOREIGN KEY(ID_USUARIO) REFERENCES USUARIOS(ID_USUARIO),
    CONSTRAINT FK_UP_PROYECTO FOREIGN KEY(ID_PROYECTO) REFERENCES PROYECTO(ID_PROYECTO)
);

CREATE TABLE ETIQUETA(
    ID_ETIQUETA INT AUTO_INCREMENT,
    NOMETIQ VARCHAR(30) NOT NULL,
    COLOR VARCHAR(20) NOT NULL,
    ID_PROYECTO INT NOT NULL,
    CONSTRAINT PK_ETIQUETA PRIMARY KEY(ID_ETIQUETA),
    CONSTRAINT UQ_ETIQUETA_PROYECTO UNIQUE(ID_PROYECTO, NOMETIQ),
    CONSTRAINT FK_ETIQUETA_PROYECTO FOREIGN KEY(ID_PROYECTO) REFERENCES PROYECTO(ID_PROYECTO)
);

CREATE TABLE TABLERO(
    ID_TABLERO INT AUTO_INCREMENT,
    NOMTAB VARCHAR(50) NOT NULL,
    ID_PROYECTO INT NOT NULL,
    FECHA_CREACION DATE NOT NULL DEFAULT (CURRENT_DATE),
    CONSTRAINT PK_TABLERO PRIMARY KEY(ID_TABLERO),
    CONSTRAINT FK_TABLERO_PROYECTO FOREIGN KEY(ID_PROYECTO) REFERENCES PROYECTO(ID_PROYECTO)
);

CREATE TABLE LISTA(
    ID_LISTA INT AUTO_INCREMENT,
    NOMBLIST VARCHAR(50) NOT NULL,
    ID_TABLERO INT NOT NULL,
    POSICION INT NOT NULL,
    DESCRIPLIST VARCHAR(150) NULL,
    CONSTRAINT PK_LISTA PRIMARY KEY(ID_LISTA),
    CONSTRAINT FK_LISTA_TABLERO FOREIGN KEY(ID_TABLERO) REFERENCES TABLERO(ID_TABLERO)
);

CREATE TABLE TARJETA(
    ID_TARJETA INT AUTO_INCREMENT,
    NOMBTARJ VARCHAR(50) NOT NULL,
    ID_LISTA INT NOT NULL,
    DESCRIPTARJ VARCHAR(150) NULL,
    FECHA_CREACION DATE NOT NULL DEFAULT (CURRENT_DATE),
    FECHA_VENCIMIENTO DATE NULL,
    ESTADO VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    POSICION INT NOT NULL,
    ID_RESPONSABLE INT NULL,
    CONSTRAINT PK_TARJETA PRIMARY KEY(ID_TARJETA),
    CONSTRAINT CK_TARJETA_FECHAS CHECK (FECHA_VENCIMIENTO IS NULL OR FECHA_VENCIMIENTO >= FECHA_CREACION),
    CONSTRAINT FK_TARJETA_LISTA FOREIGN KEY(ID_LISTA) REFERENCES LISTA(ID_LISTA),
    CONSTRAINT FK_TARJETA_RESPONSABLE FOREIGN KEY(ID_RESPONSABLE) REFERENCES USUARIO_PROYECTO(ID_USUARIO_PROYECTO)
);

CREATE TABLE TARJETA_ETIQUETA(
    ID_TARJETA INT NOT NULL,
    ID_ETIQUETA INT NOT NULL,
    CONSTRAINT PK_TARJETA_ETIQUETA PRIMARY KEY(ID_TARJETA, ID_ETIQUETA),
    CONSTRAINT FK_TE_TARJETA FOREIGN KEY(ID_TARJETA) REFERENCES TARJETA(ID_TARJETA),
    CONSTRAINT FK_TE_ETIQUETA FOREIGN KEY(ID_ETIQUETA) REFERENCES ETIQUETA(ID_ETIQUETA)
);

CREATE TABLE COMENTARIO(
    ID_COMENTARIO INT AUTO_INCREMENT,
    TEXTO TEXT NOT NULL,
    FECHA_CREACION DATE NOT NULL DEFAULT (CURRENT_DATE),
    ID_USUARIO INT NOT NULL,
    ID_TARJETA INT NOT NULL,
    CONSTRAINT PK_COMENTARIO PRIMARY KEY(ID_COMENTARIO),
    CONSTRAINT FK_COMENTARIO_USUARIOS FOREIGN KEY(ID_USUARIO) REFERENCES USUARIOS(ID_USUARIO),
    CONSTRAINT FK_COMENTARIO_TARJETA FOREIGN KEY(ID_TARJETA) REFERENCES TARJETA(ID_TARJETA)
);